const GRAVITY_TABLE = [
  1000, 850, 720, 600, 500, 410, 330, 260, 200, 155,
  120, 95, 75, 60, 48, 38, 30, 24, 19, 15, 12,
];

function gravityFor(level) {
  return GRAVITY_TABLE[Math.min(level - 1, GRAVITY_TABLE.length - 1)];
}

